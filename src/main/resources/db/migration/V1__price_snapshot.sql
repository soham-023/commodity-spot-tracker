CREATE TABLE price_snapshot (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity      VARCHAR(40)    NOT NULL,
    source         VARCHAR(40)    NOT NULL,
    market         VARCHAR(80)    NOT NULL,
    variety        VARCHAR(80)    NOT NULL DEFAULT '',
    price_type     VARCHAR(10)    NOT NULL,
    contract_month VARCHAR(7)     NOT NULL DEFAULT '',
    price          NUMERIC(12, 2) NOT NULL,
    min_price      NUMERIC(12, 2),
    max_price      NUMERIC(12, 2),
    price_date     DATE           NOT NULL,
    fetched_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_price_snapshot_natural
        UNIQUE (source, market, variety, price_type, contract_month, price_date)
);

CREATE INDEX ix_price_snapshot_commodity_date ON price_snapshot (commodity, price_date);
