-- Data scraped from the NCDEX product page (/products/<symbol>).

CREATE TABLE contract_expiry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol      VARCHAR(20) NOT NULL,
    expiry_date DATE        NOT NULL,
    first_seen  DATE        NOT NULL,
    last_seen   DATE        NOT NULL,
    CONSTRAINT uk_contract_expiry UNIQUE (symbol, expiry_date)
);

-- Margins are % of contract value, one row per NCCL margin file, margin date and expiry.
CREATE TABLE daily_margin (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol           VARCHAR(20)   NOT NULL,
    margin_date      DATE          NOT NULL,
    file_type        VARCHAR(20)   NOT NULL,
    expiry_date      DATE          NOT NULL,
    initial_margin   NUMERIC(6, 2),
    extreme_margin   NUMERIC(6, 2),
    additional_pem   NUMERIC(6, 2),
    total_margin     NUMERIC(6, 2) NOT NULL,
    additional_long  NUMERIC(6, 2),
    additional_short NUMERIC(6, 2),
    special_long     NUMERIC(6, 2),
    special_short    NUMERIC(6, 2),
    fetched_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_daily_margin UNIQUE (symbol, margin_date, file_type, expiry_date)
);

CREATE INDEX ix_daily_margin_symbol_date ON daily_margin (symbol, margin_date);

-- Delivery-location premium (+) / discount (-) over the basis quality, in %, as published on as_of_date.
CREATE TABLE premium_discount (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol         VARCHAR(20)   NOT NULL,
    expiry_date    DATE          NOT NULL,
    as_of_date     DATE          NOT NULL,
    basis_location VARCHAR(80)   NOT NULL,
    location       VARCHAR(160)  NOT NULL,
    quality        VARCHAR(120)  NOT NULL,
    centre         VARCHAR(80)   NOT NULL,
    premium_pct    NUMERIC(6, 2) NOT NULL,
    is_basis       BOOLEAN       NOT NULL DEFAULT FALSE,
    fetched_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_premium_discount UNIQUE (symbol, expiry_date, location, as_of_date)
);
