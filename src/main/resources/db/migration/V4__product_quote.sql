-- Last traded price from the NCDEX product page header, one row per symbol and market date.
-- NCDEX does not say which expiry the LTP belongs to, so it is kept apart from price_snapshot.
CREATE TABLE product_quote (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol            VARCHAR(20)    NOT NULL,
    quote_date        DATE           NOT NULL,
    last_traded_price NUMERIC(14, 2) NOT NULL,
    price_change      NUMERIC(14, 2),
    fetched_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_product_quote UNIQUE (symbol, quote_date)
);
